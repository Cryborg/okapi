fn main() {
    let mut arguments = std::env::args().skip(1);
    let screen = arguments.next().unwrap_or_else(|| String::from("results"));
    let out = arguments.next().unwrap_or_else(|| format!("{screen}.png"));
    let (width, height) = if screen.ends_with("-small") {
        SMALL
    } else {
        LARGE
    };
    let window = MinimalSoftwareWindow::new(RepaintBufferType::NewBuffer);
    slint::platform::set_platform(Box::new(Offscreen(window.clone()))).unwrap();
    let app = ui::AppWindow::new().unwrap();
    slint::select_bundled_translation("").unwrap();
    match screen.as_str() {
        "results" => results(&app, false),
        "folded" => results(&app, true),
        "browser" => browser(&app),
        "receipt" => receipt(&app),
        "choosing" => choosing(&app),
        "scanning" => scanning(&app),
        "cleaning" => cleaning(&app),
        "ended" => ended(&app),
        "about" => app.set_page(ui::Page::About),
        "home" | "home-small" => home(&app),
        "home-folded" => {
            home(&app);
            app.set_sidebar_chosen_folded(true);
        }
        "home-disks" => home_tall(&app, true),
        "home-customize" | "home-move" => {
            home(&app);
            let dashboard = app.global::<ui::Dashboard>();
            dashboard.set_editing(true);
            // Disques picked up with the keyboard.
            dashboard.set_moving(ui::Moving {
                shown: screen == "home-move",
                row: 1,
                to: 1,
                by_pointer: false,
            });
            // The tile after Système, in each number of columns.
            dashboard.set_tile(ModelRc::new(VecModel::from(vec![
                place(0, 5, 1, 1),
                place(1, 4, 1, 1),
                place(0, 3, 1, 1),
                place(0, 3, 1, 1),
            ])));
            dashboard.set_rows_with_tile(ModelRc::new(VecModel::from(vec![6, 5, 4, 4])));
            dashboard.set_toast(ui::Toast {
                shown: screen == "home-customize",
                kind: ui::WidgetKind::Disks,
            });
        }
        "home-memory" => home_tall(&app, false),
        "disk-start" => disk(&app, ui::DiskStep::Start),
        "disk-scanning" => disk(&app, ui::DiskStep::Scanning),
        "disk-result" | "disk-result-small" => disk(&app, ui::DiskStep::Result),
        "updates" | "updates-open" | "updates-open-small" | "updates-searching"
        | "updates-uptodate" | "updates-locked" => {
            let state = match screen.trim_end_matches("-small") {
                "updates" => "pending",
                "updates-open" => "pending-open",
                other => other.trim_start_matches("updates-"),
            };
            updates(&app, state);
        }
        "apps" => apps(&app, true, false),
        "apps-small" => apps(&app, false, false),
        "apps-uninstall" => apps(&app, true, true),
        "apps-uninstall-flatpak" => apps_flatpak(&app),
        "apps-leftovers" => apps_leftovers(&app, false),
        "apps-leftovers-empty" => apps_leftovers(&app, true),
        other => panic!(
            "no screen {other}: results, folded, browser, receipt, choosing, scanning, cleaning, ended, about, home, home-small, home-folded, home-disks, home-memory, home-customize, home-move, disk-start, disk-scanning, disk-result, disk-result-small, updates, updates-open, updates-open-small, updates-searching, updates-uptodate, updates-locked, apps, apps-small, apps-uninstall, apps-uninstall-flatpak, apps-leftovers, apps-leftovers-empty"
        ),
    }
    window.set_size(PhysicalSize::new(width, height));
    app.show().unwrap();
    slint::platform::update_timers_and_animations();
    let mut pixels = vec![PremultipliedRgbaColor::default(); (width * height) as usize];
    window.draw_if_needed(|renderer| {
        renderer.render(&mut pixels, width as usize);
    });
    let mut encoder = png::Encoder::new(BufWriter::new(File::create(&out).unwrap()), width, height);
    encoder.set_color(png::ColorType::Rgb);
    encoder.set_depth(png::BitDepth::Eight);
    let bytes: Vec<u8> = pixels
        .iter()
        .flat_map(|pixel| [pixel.red, pixel.green, pixel.blue])
        .collect();
    encoder
        .write_header()
        .unwrap()
        .write_image_data(&bytes)
        .unwrap();
    println!("{out}");
}
