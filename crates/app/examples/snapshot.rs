fn size(whole: i32, tenths: i32, unit: ui::SizeUnit) -> ui::Size {
    ui::Size {
        whole,
        tenths,
        has_tenths: unit != ui::SizeUnit::Byte,
        unit,
    }
}

/// What the machine would give in `language`: a text of its own (a folder's
/// name, a package's summary), which Okapi shows as it is.
fn said(language: Language, french: &'static str, english: &'static str) -> &'static str {
    match language {
        Language::French => french,
        Language::English => english,
    }
}

/// The description, in `language`, of the Linux rule shown as `label`.
fn description_of(label: &str, language: Language) -> slint::SharedString {
    let rules = okapi_rules::RuleSet::embedded(okapi_rules::Os::Linux).unwrap();
    let system = rules.system();
    let browsers = rules.browsers();
    let directories = browsers.chromium_cache_directories();
    let english = system
        .clean_targets()
        .iter()
        .map(|target| (target.subcategory(), target.description()))
        .chain(
            system
                .single_file_targets()
                .iter()
                .map(|target| (target.subcategory(), target.description())),
        )
        .chain(
            rules
                .apps()
                .iter()
                .chain(rules.gaming())
                .chain(rules.gpu_cache())
                .map(|rule| (rule.name(), rule.description())),
        )
        .chain(
            directories
                .profile()
                .iter()
                .chain(directories.shared())
                .chain(browsers.firefox_cache_directories())
                .map(|directory| (directory.label(), directory.description())),
        )
        .find_map(|(name, description)| (name.as_str() == label).then_some(description))
        .flatten()
        .unwrap();
    // A maintenance's description shows its limits; another has no
    // placeholder to fill.
    let values = if label == "Docker Build Cache" {
        okapi_tools::docker::DESCRIPTION_VALUES
    } else {
        okapi_helper::JOURNAL_DESCRIPTION_VALUES
    };
    okapi_rules::filled(okapi_rules::description(language, english.as_str()), values).into()
}

fn row(
    category: ui::CategoryKind,
    label: &str,
    badge: ui::ResultBadge,
    checked: bool,
    language: Language,
) -> ui::ResultRow {
    ui::ResultRow {
        kind: ui::RowKind::Group,
        nested: false,
        category,
        label: okapi_rules::label(language, label).into(),
        description: description_of(label, language),
        explained: false,
        checked_by_default: badge == ui::ResultBadge::Preselected,
        state: if checked {
            ui::CheckState::Checked
        } else {
            ui::CheckState::Unchecked
        },
        enabled: badge != ui::ResultBadge::Admin,
        folded: false,
        hidden: false,
        badge,
        note: match badge {
            ui::ResultBadge::Admin => ui::RowNote::Locked,
            ui::ResultBadge::ToChoose => ui::RowNote::CacheReset,
            ui::ResultBadge::Preselected => ui::RowNote::None,
        },
        entries: 1528,
        size: size(936, 7, ui::SizeUnit::Megabyte),
    }
}

