/// The duplicates screen at `scene`.
fn duplicates(window: &ui::AppWindow, scene: DuplicateScene, language: Language) {
    use ui::SizeUnit::Gigabyte;
    window.set_page(ui::Page::Duplicates);
    let duplicates = window.global::<ui::Duplicates>();
    duplicates.set_min_size(size(1, 0, ui::SizeUnit::Megabyte));
    duplicates.set_searched_names(
        said(
            language,
            "Documents, Images, Vidéos, Téléchargements",
            "Documents, Pictures, Videos, Downloads",
        )
        .into(),
    );
    duplicates.set_compared(said(language, "12\u{202F}840", "12,840").into());
    duplicates.set_minutes(2);
    duplicates.set_rule_said(true);
    duplicates.set_folder_names(said(language, PERSONAL_NAMES.0, PERSONAL_NAMES.1).into());
    if matches!(scene, DuplicateScene::Start | DuplicateScene::StartHome) {
        // Two of the folders left out: the home folder's box is partly
        // checked.
        let folders = personal_folders(language, &[2, 5]);
        duplicates.set_chosen_folders(4);
        duplicates.set_folders_state(ui::FoldersState::Read);
        duplicates.set_folders(ModelRc::new(VecModel::from(folders)));
        duplicates.set_home_path("/home/franck".into());
        duplicates.set_whole_home(scene == DuplicateScene::StartHome);
        duplicates.set_step(ui::ToolStep::Start);
        return;
    }
    duplicates.set_step(ui::ToolStep::Result);
    if scene == DuplicateScene::Empty {
        return;
    }
    let downloads = said(language, "~/Téléchargements", "~/Downloads");
    let videos = said(language, "~/Vidéos", "~/Videos");
    let film = |folder: &str| format!("{folder}/vacances-2025.mp4");
    let first = duplicate_copy(0, &film(downloads), (2, 8, 2025), ui::KeptWhy::None);
    let mut kept = duplicate_copy(0, &film(videos), (30, 7, 2025), ui::KeptWhy::Outside);
    kept.why_first = said(language, "Téléchargements", "Downloads").into();
    kept.last = true;
    kept.checkable = false;
    let rows = vec![
        duplicate_head("vacances-2025.mp4", 2, size(2, 4, Gigabyte), true, 1),
        first,
        kept,
        duplicate_head(
            "ubuntu-24.04.2-desktop-amd64.iso",
            3,
            size(4, 8, Gigabyte),
            false,
            2,
        ),
    ];
    duplicates.set_rows(ModelRc::new(VecModel::from(rows)));
    duplicates.set_groups(2);
    duplicates.set_duplicated(size(7, 2, Gigabyte));
    duplicates.set_current(1);
    duplicates.set_chosen_size(size(7, 2, Gigabyte));
    duplicates.set_chosen_files(3);
    duplicates.set_chosen_groups(2);
    duplicates.set_confirming(scene == DuplicateScene::Confirm);
    if scene == DuplicateScene::Quick {
        // Opened as by its button, once the page is laid out at its size.
        window
            .window()
            .set_size(PhysicalSize::new(LARGE.0, LARGE.1));
        window.show().unwrap();
        slint::platform::update_timers_and_animations();
        i_slint_backend_testing::ElementHandle::find_by_accessible_label(
            window,
            "Sélection rapide",
        )
        .chain(
            i_slint_backend_testing::ElementHandle::find_by_accessible_label(
                window,
                "Quick selection",
            ),
        )
        .next()
        .unwrap()
        .invoke_accessible_default_action();
        slint::platform::update_timers_and_animations();
    }
}

/// The large files screen at `scene`.
fn large_files(window: &ui::AppWindow, scene: LargeScene, language: Language) {
    use ui::SizeUnit::{Gigabyte, Megabyte};
    window.set_page(ui::Page::LargeFiles);
    let large = window.global::<ui::LargeFiles>();
    let names = said(language, PERSONAL_NAMES.0, PERSONAL_NAMES.1);
    large.set_folders_state(ui::FoldersState::Read);
    large.set_folders(ModelRc::new(VecModel::from(personal_folders(
        language,
        &[],
    ))));
    large.set_chosen_folders(6);
    large.set_home_path("/home/franck".into());
    large.set_min_size(size(50, 0, Megabyte));
    large.set_searched_home(scene == LargeScene::Outside);
    large.set_searched_names(names.into());
    large.set_folder_names(names.into());
    let floors = vec![
        size(100, 0, Megabyte),
        size(500, 0, Megabyte),
        size(1, 0, Gigabyte),
        size(5, 0, Gigabyte),
    ];
    large.set_floors(ModelRc::new(VecModel::from(floors)));
    let ages = [(3, false), (6, false), (1, true), (2, true)]
        .map(|(count, years)| ui::AgeShown { count, years });
    large.set_ages(ModelRc::new(VecModel::from(ages.to_vec())));
    match scene {
        LargeScene::Start => large.set_step(ui::ToolStep::Start),
        LargeScene::Searching | LargeScene::Stopped => {
            large.set_step(ui::ToolStep::Searching);
            large.set_phase(if scene == LargeScene::Stopped {
                ui::SearchPhase::Stopped
            } else {
                ui::SearchPhase::Running
            });
            large.set_files_listed(said(language, "18\u{202F}400", "18,400").into());
            large.set_files_count(18_400);
            large.set_found("31".into());
            large.set_found_count(31);
        }
        LargeScene::Receipt => large_receipt(&large, language),
        _ => large_result(&large, scene, language),
    }
}

/// The screen `screen` reading what it shows (the note beside its title):
/// the last screens `main` looks for, a name unknown said with them all.
fn reading_scene(app: &ui::AppWindow, screen: &str, language: Language) {
    match screen {
        "history-reading" => {
            history(app, true, language);
            app.global::<ui::History>()
                .set_reading(ui::HistoryReading::Reading);
        }
        "disk-start-reading" => {
            disk(app, ui::DiskStep::Start, language);
            let disk = app.global::<ui::DiskUsage>();
            disk.set_volumes_state(ui::DiskVolumes::Reading);
            disk.set_volumes(ModelRc::default());
        }
        "large-start-reading" => {
            large_files(app, LargeScene::Start, language);
            let large = app.global::<ui::LargeFiles>();
            large.set_folders_state(ui::FoldersState::Reading);
            large.set_folders(ModelRc::default());
            large.set_chosen_folders(0);
        }
        "duplicates-start-reading" => {
            duplicates(app, DuplicateScene::Start, language);
            let duplicates = app.global::<ui::Duplicates>();
            duplicates.set_folders_state(ui::FoldersState::Reading);
            duplicates.set_folders(ModelRc::default());
            duplicates.set_chosen_folders(0);
        }
        "apps-reading" => {
            apps(app, false, false, language);
            // As a reading leaves it: nothing listed, nothing dated yet.
            let apps = app.global::<ui::Apps>();
            apps.set_reading(true);
            apps.set_lines(ModelRc::default());
            apps.set_minutes_ago(-1);
        }
        "apps-leftovers-reading" => {
            apps_leftovers(app, false, language);
            app.global::<ui::Leftovers>().set_analysing(true);
        }
        "apps-old-versions-reading" => {
            apps_old_versions(app, "apps-old-versions", language);
            app.global::<ui::OldVersions>().set_finding(true);
        }
        other => panic!(
            "no screen {other} (any one in English with -en, dark with -dark, both with -en-dark): results, results-small, results-sorted, folded, results-docker, results-by-hand, browser, receipt, choosing, scanning, cleaning, ended, about, home, home-small, home-social, home-folded, groups-closed, groups-closed-small, home-disks, home-updates, home-updates-uptodate, home-memory, home-customize, home-move, disk-start, disk-start-reading, disk-scanning, disk-result, disk-result-small, disk-result-keys, updates, updates-open, updates-open-small, updates-searching, updates-uptodate, updates-locked, apps, apps-small, apps-reading, apps-uninstall, apps-uninstall-flatpak, apps-leftovers, apps-leftovers-empty, apps-leftovers-reading, apps-old-versions, apps-old-versions-confirm, apps-old-versions-reading, settings, settings-trash, history, history-small, history-update, history-empty, history-reading, large-start, large-start-reading, large-searching, large-stopped, large-result, large-smallest, large-blocked, large-outside, large-filtered, large-nomatch, large-empty, large-confirm, large-confirm-filtered, large-receipt, duplicates-start, duplicates-start-reading, duplicates-start-home, duplicates-result, duplicates-empty, duplicates-confirm, duplicates-quick (each also -small)"
        ),
    }
}

fn main() {
    let mut arguments = std::env::args().skip(1);
    let asked = arguments.next().unwrap_or_else(|| String::from("results"));
    let out = arguments.next().unwrap_or_else(|| format!("{asked}.png"));
    // Any screen in the dark scheme: its name followed by `-dark`.
    let (screen, dark) = asked
        .strip_suffix("-dark")
        .map_or((asked.as_str(), false), |screen| (screen, true));
    // Any screen in English: its name followed by `-en`, before `-dark`.
    let (screen, language) = screen
        .strip_suffix("-en")
        .map_or((screen, Language::French), |screen| {
            (screen, Language::English)
        });
    let (width, height) = if screen.ends_with("-small") {
        SMALL
    } else if screen.ends_with("-social") {
        SOCIAL
    } else {
        LARGE
    };
    let window = MinimalSoftwareWindow::new(RepaintBufferType::NewBuffer);
    slint::platform::set_platform(Box::new(Offscreen(window.clone()))).unwrap();
    let app = ui::AppWindow::new().unwrap();
    // The French source is the bundle's empty language, as in the interface.
    slint::select_bundled_translation(said(language, "", "en")).unwrap();
    if dark {
        app.global::<ui::Preferences>().invoke_show_theme(true);
    }
    match screen {
        "results" | "results-small" => results(&app, false, language),
        "results-sorted" => results_sorted(&app, language),
        "folded" => results(&app, true, language),
        "results-docker" => results_of(
            &app,
            language,
            &[ui::RowNote::Daemon, ui::RowNote::DaemonRefused],
        ),
        "results-by-hand" => results_of(&app, language, &[ui::RowNote::ByHand]),
        "browser" => browser(&app, language),
        "receipt" => receipt(&app),
        "choosing" => choosing(&app),
        "scanning" => scanning(&app),
        "cleaning" => cleaning(&app),
        "ended" => ended(&app),
        "about" => app.set_page(ui::Page::About),
        "home" | "home-small" | "home-social" => home(&app, language),
        "home-folded" => {
            home(&app, language);
            app.set_sidebar_chosen_folded(true);
        }
        "groups-closed" | "groups-closed-small" => groups_closed(&app, language),
        "home-disks" => home_tall(&app, true, language),
        "home-updates" => home_updates(&app, "pending", language),
        "home-updates-uptodate" => home_updates(&app, "uptodate", language),
        "home-customize" | "home-move" => home_customize(&app, screen == "home-move", language),
        "home-memory" => home_tall(&app, false, language),
        "disk-start" => disk(&app, ui::DiskStep::Start, language),
        // With the keys, running first: its end gives the list the focus.
        "disk-scanning" | "disk-result-keys" => disk(&app, ui::DiskStep::Scanning, language),
        "disk-result" | "disk-result-small" => disk(&app, ui::DiskStep::Result, language),
        "updates" | "updates-open" | "updates-open-small" | "updates-searching"
        | "updates-uptodate" | "updates-locked" => {
            let state = match screen.trim_end_matches("-small") {
                "updates" => "pending",
                "updates-open" => "pending-open",
                other => other.trim_start_matches("updates-"),
            };
            updates(&app, state, language);
        }
        "apps" => apps(&app, true, false, language),
        "apps-small" => apps(&app, false, false, language),
        "apps-uninstall" => apps(&app, true, true, language),
        "apps-uninstall-flatpak" => apps_flatpak(&app, language),
        "apps-leftovers" => apps_leftovers(&app, false, language),
        "apps-leftovers-empty" => apps_leftovers(&app, true, language),
        old if old.starts_with("apps-old-versions") && !old.ends_with("-reading") => {
            apps_old_versions(&app, old, language);
        }
        "settings" => settings(&app),
        "settings-trash" => settings_trash(&app),
        "history" | "history-small" => history(&app, false, language),
        "history-update" => history_update(&app, language),
        "history-empty" => history(&app, true, language),
        other if let Some(scene) = LargeScene::named(other.trim_end_matches("-small")) => {
            large_files(&app, scene, language);
        }
        other if let Some(scene) = DuplicateScene::named(other.trim_end_matches("-small")) => {
            duplicates(&app, scene, language);
        }
        // Else a screen reading what it shows, or none.
        other => reading_scene(&app, other, language),
    }
    window.set_size(PhysicalSize::new(width, height));
    app.show().unwrap();
    slint::platform::update_timers_and_animations();
    if screen == "disk-result-keys" {
        // Ended, the keyboard on the name cut short.
        disk(&app, ui::DiskStep::Result, language);
        app.global::<ui::DiskUsage>().set_current(2);
        // `changed` handlers run on the next turns of the event loop.
        slint::platform::update_timers_and_animations();
        slint::platform::update_timers_and_animations();
    }
    write_png(&window, width, height, &out);
    println!("{out}");
}

/// Draws `window`, of `width` by `height` pixels, into the PNG file `out`.
fn write_png(window: &MinimalSoftwareWindow, width: u32, height: u32, out: &str) {
    let mut pixels = vec![PremultipliedRgbaColor::default(); (width * height) as usize];
    window.draw_if_needed(|renderer| {
        renderer.render(&mut pixels, width as usize);
    });
    let mut encoder = png::Encoder::new(BufWriter::new(File::create(out).unwrap()), width, height);
    encoder.set_color(png::ColorType::Rgb);
    encoder.set_depth(png::BitDepth::Eight);
    let bytes: Vec<u8> = pixels
        .iter()
        .flat_map(|pixel| [pixel.red, pixel.green, pixel.blue])
        .collect();
    encoder
        .write_header()
        .unwrap()
        .write_image_data(&bytes)
        .unwrap();
}
