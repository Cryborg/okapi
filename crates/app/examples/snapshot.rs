//! Draws a screen of the interface into a PNG, with made-up content, so that
//! its layout can be looked at without a display:
//! `cargo run -p okapi-app --example snapshot -- results /path/to/out.png`.
//! A development tool: it never reads the machine and never cleans.
#![expect(clippy::unwrap_used, reason = "a development tool fails by panicking")]

use std::fs::File;
use std::io::BufWriter;
use std::rc::Rc;

use slint::platform::software_renderer::{
    MinimalSoftwareWindow, PremultipliedRgbaColor, RepaintBufferType,
};
use slint::platform::{Platform, WindowAdapter};
use slint::{ComponentHandle as _, ModelRc, PhysicalSize, VecModel};

/// The interface, as Slint generates it from `ui/`.
mod ui {
    #![expect(
        missing_debug_implementations,
        clippy::unwrap_used,
        clippy::todo,
        reason = "code generated by Slint"
    )]
    slint::include_modules!();
}

/// The sizes the mockups draw the window at.
const LARGE: (u32, u32) = (1280, 800);
const SMALL: (u32, u32) = (960, 640);

struct Offscreen(Rc<MinimalSoftwareWindow>);

impl Platform for Offscreen {
    fn create_window_adapter(&self) -> Result<Rc<dyn WindowAdapter>, slint::PlatformError> {
        Ok(self.0.clone())
    }
}

fn size(whole: i32, tenths: i32, unit: ui::SizeUnit) -> ui::Size {
    ui::Size {
        whole,
        tenths,
        has_tenths: unit != ui::SizeUnit::Byte,
        unit,
    }
}

fn row(
    category: ui::CategoryKind,
    label: &str,
    badge: ui::ResultBadge,
    checked: bool,
) -> ui::ResultRow {
    ui::ResultRow {
        kind: ui::RowKind::Group,
        nested: false,
        category,
        // In French, as the window: the longer labels of the two.
        label: okapi_rules::label(okapi_rules::Language::French, label).into(),
        state: if checked {
            ui::CheckState::Checked
        } else {
            ui::CheckState::Unchecked
        },
        enabled: badge != ui::ResultBadge::Admin,
        folded: false,
        hidden: false,
        badge,
        admin: if badge == ui::ResultBadge::Admin {
            ui::AdminRow::Locked
        } else {
            ui::AdminRow::None
        },
        entries: 1528,
        size: size(936, 7, ui::SizeUnit::Megabyte),
    }
}

fn header(category: ui::CategoryKind, folded: bool) -> ui::ResultRow {
    ui::ResultRow {
        kind: ui::RowKind::Category,
        nested: false,
        category,
        label: "".into(),
        state: ui::CheckState::Partial,
        enabled: true,
        folded,
        hidden: false,
        badge: ui::ResultBadge::Preselected,
        admin: ui::AdminRow::None,
        entries: 86_300,
        size: size(10, 8, ui::SizeUnit::Gigabyte),
    }
}

