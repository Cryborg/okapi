/// The Home page with only Disques and Mémoire, at their two tallest sizes:
/// `disks` Large and Memory Tall, or the other way round.
fn home_tall(window: &ui::AppWindow, disks_large: bool) {
    home(window);
    let (large, tall) = if disks_large {
        (ui::WidgetKind::Disks, ui::WidgetKind::Memory)
    } else {
        (ui::WidgetKind::Memory, ui::WidgetKind::Disks)
    };
    let large_place = place(0, 0, 2, 2);
    let tall_place = place(2, 0, 1, 2);
    let cells = vec![
        cell(large, ui::WidgetSize::Large, vec![large_place; 4]),
        cell(tall, ui::WidgetSize::Tall, vec![tall_place; 4]),
    ];
    let dashboard = window.global::<ui::Dashboard>();
    dashboard.set_cells(ModelRc::new(VecModel::from(cells)));
    dashboard.set_rows(ModelRc::new(VecModel::from(vec![2; 4])));
}

fn main() {
    let mut arguments = std::env::args().skip(1);
    let screen = arguments.next().unwrap_or_else(|| String::from("results"));
    let out = arguments.next().unwrap_or_else(|| format!("{screen}.png"));
    let (width, height) = if screen == "home-small" { SMALL } else { LARGE };
    let window = MinimalSoftwareWindow::new(RepaintBufferType::NewBuffer);
    slint::platform::set_platform(Box::new(Offscreen(window.clone()))).unwrap();
    let app = ui::AppWindow::new().unwrap();
    slint::select_bundled_translation("").unwrap();
    match screen.as_str() {
        "results" => results(&app, false),
        "folded" => results(&app, true),
        "browser" => browser(&app),
        "receipt" => receipt(&app),
        "choosing" => choosing(&app),
        "scanning" => scanning(&app),
        "cleaning" => cleaning(&app),
        "ended" => ended(&app),
        "about" => app.set_page(ui::Page::About),
        "home" | "home-small" => home(&app),
        "home-disks" => home_tall(&app, true),
        "home-customize" => {
            home(&app);
            let dashboard = app.global::<ui::Dashboard>();
            dashboard.set_editing(true);
            // The tile after Système, in each number of columns.
            dashboard.set_tile(ModelRc::new(VecModel::from(vec![
                place(0, 5, 1, 1),
                place(1, 4, 1, 1),
                place(0, 3, 1, 1),
                place(0, 3, 1, 1),
            ])));
            dashboard.set_rows_with_tile(ModelRc::new(VecModel::from(vec![6, 5, 4, 4])));
            dashboard.set_toast(ui::Toast {
                shown: true,
                kind: ui::WidgetKind::Disks,
            });
        }
        "home-memory" => home_tall(&app, false),
        other => panic!(
            "no screen {other}: results, folded, browser, receipt, choosing, scanning, cleaning, ended, about, home, home-small, home-disks, home-memory, home-customize"
        ),
    }
    window.set_size(PhysicalSize::new(width, height));
    app.show().unwrap();
    slint::platform::update_timers_and_animations();
    let mut pixels = vec![PremultipliedRgbaColor::default(); (width * height) as usize];
    window.draw_if_needed(|renderer| {
        renderer.render(&mut pixels, width as usize);
    });
    let mut encoder = png::Encoder::new(BufWriter::new(File::create(&out).unwrap()), width, height);
    encoder.set_color(png::ColorType::Rgb);
    encoder.set_depth(png::BitDepth::Eight);
    let bytes: Vec<u8> = pixels
        .iter()
        .flat_map(|pixel| [pixel.red, pixel.green, pixel.blue])
        .collect();
    encoder
        .write_header()
        .unwrap()
        .write_image_data(&bytes)
        .unwrap();
    println!("{out}");
}
