/// The results, the system category folded when `folded`.
fn results(window: &ui::AppWindow, folded: bool) {
    use ui::CategoryKind::{Apps, Browsers, System};
    use ui::ResultBadge::{Admin, Preselected, ToChoose};
    let system = [
        ("Thumbnail Cache", Preselected, true),
        ("Crash Reports", Admin, false),
        ("APT Package Cache", Admin, false),
        ("Snap App Cache", Preselected, true),
        ("Font Cache", ToChoose, false),
        ("Installer Logs", Admin, false),
        ("System Font Cache", Admin, false),
        ("Man Page Cache", Admin, false),
        ("APT Logs", Admin, false),
        ("GNOME Tracker Cache", Preselected, true),
        ("GStreamer Cache", Preselected, true),
    ];
    let mut rows = vec![header(System, folded)];
    rows.extend(system.iter().map(|(label, badge, checked)| {
        let mut line = row(System, label, *badge, *checked);
        line.hidden = folded;
        line
    }));
    rows.push(header(Browsers, false));
    let browser = |name: &str, folded| ui::ResultRow {
        kind: ui::RowKind::Browser,
        label: name.into(),
        folded,
        ..header(Browsers, false)
    };
    let cache = |label, badge, checked, hidden| ui::ResultRow {
        nested: true,
        hidden,
        ..row(Browsers, label, badge, checked)
    };
    rows.extend([
        browser("Chrome", false),
        cache("Cache", Preselected, true, false),
        cache("Code Cache", ToChoose, false, false),
        cache("GPU Cache", ToChoose, false, false),
        browser("Opera GX", true),
        cache("Cache", Preselected, true, true),
    ]);
    rows.push(header(Apps, false));
    rows.extend([
        row(Apps, "npm Cache", Preselected, true),
        row(Apps, "pip Cache", Preselected, true),
        row(Apps, "Hugging Face Xet Cache", ToChoose, false),
    ]);
    let cleaner = window.global::<ui::Cleaner>();
    cleaner.set_results(ModelRc::new(VecModel::from(rows)));
    cleaner.set_selected_entries(4);
    cleaner.set_result_entries(7);
    cleaner.set_rights_waiting(6);
    cleaner.set_selected_size(size(2, 1, ui::SizeUnit::Gigabyte));
    cleaner.set_found(size(11, 6, ui::SizeUnit::Gigabyte));
    cleaner.set_step(ui::CleanerStep::Results);
    window.set_page(ui::Page::Cleaner);
}

