/// The steps of a cleaning: kind, state, entries done of all.
fn steps(steps: &[(ui::CleanStepKind, ui::RowState, i32, i32)]) -> ModelRc<ui::CleanStep> {
    ModelRc::new(VecModel::from(
        steps
            .iter()
            .map(|&(kind, state, done, total)| ui::CleanStep {
                kind,
                state,
                done,
                total,
            })
            .collect::<Vec<_>>(),
    ))
}

