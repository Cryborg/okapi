//! Draws a screen of the interface into a PNG, with made-up content, so that
//! its layout can be looked at without a display:
//! `cargo run -p okapi-app --example snapshot -- results /path/to/out.png`.
//! A development tool: it never reads the machine and never cleans.
#![expect(clippy::unwrap_used, reason = "a development tool fails by panicking")]

use std::fs::File;
use std::io::BufWriter;
use std::rc::Rc;

use slint::platform::software_renderer::{
    MinimalSoftwareWindow, PremultipliedRgbaColor, RepaintBufferType,
};
use slint::platform::{Platform, WindowAdapter};
use slint::{ComponentHandle as _, ModelRc, PhysicalSize, VecModel};

/// The interface, as Slint generates it from `ui/`.
mod ui {
    #![expect(
        missing_debug_implementations,
        clippy::unwrap_used,
        clippy::todo,
        reason = "code generated by Slint"
    )]
    slint::include_modules!();
}

const WIDTH: u32 = 1280;
const HEIGHT: u32 = 800;

struct Offscreen(Rc<MinimalSoftwareWindow>);

impl Platform for Offscreen {
    fn create_window_adapter(&self) -> Result<Rc<dyn WindowAdapter>, slint::PlatformError> {
        Ok(self.0.clone())
    }
}

fn size(whole: i32, tenths: i32, unit: ui::SizeUnit) -> ui::Size {
    ui::Size {
        whole,
        tenths,
        has_tenths: unit != ui::SizeUnit::Byte,
        unit,
    }
}

fn row(
    category: ui::CategoryKind,
    label: &str,
    badge: ui::ResultBadge,
    checked: bool,
) -> ui::ResultRow {
    ui::ResultRow {
        kind: ui::RowKind::Group,
        nested: false,
        category,
        // In French, as the window: the longer labels of the two.
        label: okapi_rules::label(okapi_rules::Language::French, label).into(),
        state: if checked {
            ui::CheckState::Checked
        } else {
            ui::CheckState::Unchecked
        },
        enabled: badge != ui::ResultBadge::Admin,
        folded: false,
        hidden: false,
        badge,
        entries: 1528,
        size: size(936, 7, ui::SizeUnit::Megabyte),
    }
}

fn header(category: ui::CategoryKind, folded: bool) -> ui::ResultRow {
    ui::ResultRow {
        kind: ui::RowKind::Category,
        nested: false,
        category,
        label: "".into(),
        state: ui::CheckState::Partial,
        enabled: true,
        folded,
        hidden: false,
        badge: ui::ResultBadge::Preselected,
        entries: 86_300,
        size: size(10, 8, ui::SizeUnit::Gigabyte),
    }
}

/// The results, and the question about Chrome, open.
fn browser(window: &ui::AppWindow) {
    results(window, true);
    let cleaner = window.global::<ui::Cleaner>();
    cleaner.set_browser_name("Chrome".into());
    cleaner.set_browser_caches("Cache, Cache du code".into());
    cleaner.set_browser_size(size(548, 0, ui::SizeUnit::Megabyte));
    cleaner.set_browser_step(ui::BrowserStep::Ask);
    cleaner.set_browser_asking(true);
}

/// The results, the system category folded when `folded`.
fn results(window: &ui::AppWindow, folded: bool) {
    use ui::CategoryKind::{Apps, Browsers, System};
    use ui::ResultBadge::{Admin, Preselected, ToChoose};
    let system = [
        ("Thumbnail Cache", Preselected, true),
        ("Crash Reports", Admin, false),
        ("APT Package Cache", Admin, false),
        ("Snap App Cache", Preselected, true),
        ("Font Cache", ToChoose, false),
        ("Installer Logs", Admin, false),
        ("System Font Cache", Admin, false),
        ("Man Page Cache", Admin, false),
        ("APT Logs", Admin, false),
        ("GNOME Tracker Cache", Preselected, true),
        ("GStreamer Cache", Preselected, true),
    ];
    let mut rows = vec![header(System, folded)];
    rows.extend(system.iter().map(|(label, badge, checked)| {
        let mut line = row(System, label, *badge, *checked);
        line.hidden = folded;
        line
    }));
    rows.push(header(Browsers, false));
    let browser = |name: &str, folded| ui::ResultRow {
        kind: ui::RowKind::Browser,
        label: name.into(),
        folded,
        ..header(Browsers, false)
    };
    let cache = |label, badge, checked, hidden| ui::ResultRow {
        nested: true,
        hidden,
        ..row(Browsers, label, badge, checked)
    };
    rows.extend([
        browser("Chrome", false),
        cache("Cache", Preselected, true, false),
        cache("Code Cache", ToChoose, false, false),
        cache("GPU Cache", ToChoose, false, false),
        browser("Opera GX", true),
        cache("Cache", Preselected, true, true),
    ]);
    rows.push(header(Apps, false));
    rows.extend([
        row(Apps, "npm Cache", Preselected, true),
        row(Apps, "pip Cache", Preselected, true),
        row(Apps, "Hugging Face Xet Cache", ToChoose, false),
    ]);
    let cleaner = window.global::<ui::Cleaner>();
    cleaner.set_results(ModelRc::new(VecModel::from(rows)));
    cleaner.set_selected_entries(4);
    cleaner.set_result_entries(7);
    cleaner.set_selected_size(size(2, 1, ui::SizeUnit::Gigabyte));
    cleaner.set_found(size(11, 6, ui::SizeUnit::Gigabyte));
    cleaner.set_step(ui::CleanerStep::Results);
    window.set_page(ui::Page::Cleaner);
}

