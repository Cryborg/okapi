/// The rows of the system category, hidden when `folded`.
fn system_rows(folded: bool, language: Language) -> Vec<ui::ResultRow> {
    use ui::CategoryKind::System;
    use ui::ResultBadge::{Admin, Preselected, ToChoose};
    let system = [
        ("Thumbnail Cache", Preselected, true),
        ("Trash", ToChoose, false),
        ("Crash Reports", Admin, false),
        ("Journal Logs", Admin, false),
        ("APT Package Cache", Admin, false),
        ("Snap Cache", Admin, false),
        ("Snap App Cache", Preselected, true),
        ("Font Cache", ToChoose, false),
        ("Installer Logs", Admin, false),
        ("System Font Cache", Admin, false),
        ("Man Page Cache", Admin, false),
        ("APT Logs", Admin, false),
        ("GNOME Tracker Cache", Preselected, true),
        ("GStreamer Cache", Preselected, true),
    ];
    let mut rows = vec![header(System, folded)];
    rows.extend(system.iter().map(|(label, badge, checked)| {
        let mut line = row(System, label, *badge, *checked, language);
        line.hidden = folded;
        // A target only root may read, what it holds unknown; the trash,
        // gone for good; the journal's vacuum, measured by root's scan only.
        line.note = match *label {
            "Snap Cache" => ui::RowNote::Unseen,
            "Trash" => ui::RowNote::Trash,
            "Journal Logs" => ui::RowNote::Unmeasured,
            _ => line.note,
        };
        // The mockup's example, a text long enough to go to the line, or a
        // row with a note above.
        line.explained = matches!(
            *label,
            "Thumbnail Cache" | "Man Page Cache" | "Snap Cache" | "Trash" | "Journal Logs"
        );
        line
    }));
    rows
}

/// The results, the system category folded when `folded`.
fn results(window: &ui::AppWindow, folded: bool, language: Language) {
    use ui::CategoryKind::{Apps, Browsers};
    use ui::ResultBadge::{Preselected, ToChoose};
    let mut rows = system_rows(folded, language);
    // Folded, the browsers and the applications too: the user's folders show.
    rows.push(header(Browsers, folded));
    let browser = |name: &str, closed| ui::ResultRow {
        kind: ui::RowKind::Browser,
        label: name.into(),
        folded: closed,
        hidden: folded,
        ..header(Browsers, false)
    };
    let cache = |label, badge, checked, hidden| ui::ResultRow {
        nested: true,
        hidden: hidden || folded,
        ..row(Browsers, label, badge, checked, language)
    };
    rows.extend([
        browser("Chrome", false),
        cache("Cache", Preselected, true, false),
        cache("Code Cache", ToChoose, false, false),
        cache("GPU Cache", ToChoose, false, false),
        browser("Opera GX", true),
        cache("Cache", Preselected, true, true),
    ]);
    rows.push(header(Apps, folded));
    // Docker's prune, explained, and as it shows when Docker refuses the
    // user: unchecked, out of reach.
    let docker = row(Apps, "Docker Build Cache", ToChoose, false, language);
    rows.extend(
        [
            row(Apps, "npm Cache", Preselected, true, language),
            row(Apps, "pip Cache", Preselected, true, language),
            row(Apps, "Hugging Face Xet Cache", ToChoose, false, language),
            ui::ResultRow {
                note: ui::RowNote::Daemon,
                explained: true,
                ..docker.clone()
            },
            ui::ResultRow {
                note: ui::RowNote::DaemonRefused,
                enabled: false,
                ..docker
            },
            // uv's prune, the user's to run: its command as the interface's
            // one source says it (`by_hand_command`), which this example
            // cannot reach.
            ui::ResultRow {
                note: ui::RowNote::ByHand,
                explained: true,
                enabled: false,
                command: "uv cache prune".into(),
                ..row(Apps, "uv Unused Packages", ToChoose, false, language)
            },
        ]
        .map(|line| ui::ResultRow {
            hidden: folded,
            ..line
        }),
    );
    // A folder of the user's, named by its path (never translated).
    rows.push(header(ui::CategoryKind::Custom, false));
    rows.push(ui::ResultRow {
        category: ui::CategoryKind::Custom,
        label: "~/Projets/okapi/target".into(),
        description: slint::SharedString::new(),
        note: ui::RowNote::Yours,
        ..row(Apps, "pip Cache", ToChoose, false, language)
    });
    let cleaner = window.global::<ui::Cleaner>();
    cleaner.set_results(ModelRc::new(VecModel::from(rows)));
    cleaner.set_selected_entries(4);
    cleaner.set_result_entries(7);
    cleaner.set_rights_waiting(7);
    cleaner.set_selected_size(size(2, 1, ui::SizeUnit::Gigabyte));
    cleaner.set_found(size(11, 6, ui::SizeUnit::Gigabyte));
    cleaner.set_step(ui::CleanerStep::Results);
    window.set_page(ui::Page::Cleaner);
}

