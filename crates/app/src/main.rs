//! Okapi desktop application (Slint).

use std::io::{self, Write as _};
use std::process::ExitCode;

use okapi_store::journal;
use slint::ComponentHandle as _;

/// The interface, as Slint generates it from `ui/`.
mod ui {
    #![expect(
        missing_debug_implementations,
        clippy::unwrap_used,
        reason = "code generated by Slint: no Debug, and its own invariants unwrapped"
    )]
    slint::include_modules!();
}

use ui::AppWindow;

/// A diagnostic for whoever launched the app from a terminal, in English: no
/// window can say it (not yet, or not at all). Never panics on a closed
/// standard error.
fn diagnostic(message: &str) {
    let _ = writeln!(io::stderr(), "okapi-app: {message}");
}

fn main() -> ExitCode {
    // Never as root, as the command line: its journal would belong to root in
    // the user's directory.
    if okapi_platform::running_as_root() {
        diagnostic("refusing to run as root");
        return ExitCode::FAILURE;
    }
    let on_write_failure: journal::WriteFailure = Box::new(|error| {
        diagnostic(&format!("the journal can no longer be written: {error}"));
    });
    let rotation = match journal::start(journal::APP_FILE, false, on_write_failure) {
        Ok((_, rotation)) => Some(rotation),
        Err(unavailable) => {
            diagnostic(&format!("running without a journal: {unavailable}"));
            None
        }
    };
    let _app = tracing::info_span!("app", pid = std::process::id()).entered();
    if let Some(rotation) = &rotation {
        rotation.trace();
    }
    journal::trace_panics();
    // What the system locale is read from (`LANGUAGE` first); an unknown
    // language shows the French source.
    let locale = |name| std::env::var(name).ok();
    tracing::info!(
        version = env!("CARGO_PKG_VERSION"),
        language = locale("LANGUAGE"),
        lc_all = locale("LC_ALL"),
        lc_messages = locale("LC_MESSAGES"),
        lang = locale("LANG"),
        "app started"
    );
    let window = match AppWindow::new() {
        Ok(window) => window,
        Err(error) => {
            tracing::error!(error = %error, detail = ?error, "window not created");
            diagnostic(&format!("no window: {error}"));
            return ExitCode::FAILURE;
        }
    };
    tracing::info!("window created");
    match window.run() {
        Ok(()) => {
            tracing::info!("app closed");
            ExitCode::SUCCESS
        }
        Err(error) => {
            tracing::error!(error = %error, detail = ?error, "event loop failed");
            diagnostic(&format!("the event loop failed: {error}"));
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use std::time::Duration;

    use super::*;

    fn shows(window: &AppWindow) -> (f32, bool) {
        (window.get_splash_opacity(), window.get_splash_visible())
    }

    /// Moves the clock on and runs what was due: timers, then animations.
    fn advance(milliseconds: u64) {
        i_slint_backend_testing::mock_elapsed_time(Duration::from_millis(milliseconds));
        slint::platform::update_timers_and_animations();
    }

    #[test]
    fn the_splash_shows_then_fades_out_and_leaves() {
        i_slint_backend_testing::init_no_event_loop();
        let window = AppWindow::new().unwrap();
        let (opacity, visible) = shows(&window);
        assert!(opacity > 0.99 && visible, "shown from the first frame");
        advance(1_199);
        let (opacity, visible) = shows(&window);
        assert!(opacity > 0.99 && visible, "held 1.2 s: {opacity}");
        advance(1);
        advance(150);
        let (quarter, visible) = shows(&window);
        // The easing decelerates: a quarter of the time is well past a
        // quarter of the fade (linear would still be at 0.75).
        assert!(quarter < 0.6 && visible, "fading: {quarter}");
        advance(300);
        let (later, visible) = shows(&window);
        assert!(later < quarter && later > 0.0 && visible, "fading: {later}");
        advance(149);
        let (opacity, visible) = shows(&window);
        assert!(opacity > 0.0 && visible, "still there just before the end");
        advance(1);
        let (opacity, visible) = shows(&window);
        assert!(
            opacity < 0.001 && !visible,
            "gone after the fade: {opacity}"
        );
        advance(3_600);
        let (opacity, visible) = shows(&window);
        assert!(opacity < 0.001 && !visible, "never back");
    }
}
