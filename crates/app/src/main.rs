    /// Every `@tr` text of `ui/`, with the component it is in (its
    /// translation context). A call this parser cannot read is a failure,
    /// never a text left unchecked.
    fn translatable_texts() -> Vec<(String, String)> {
        let directory = Path::new(env!("CARGO_MANIFEST_DIR")).join("ui");
        let mut texts = Vec::new();
        for file in fs::read_dir(directory).unwrap() {
            let path = file.unwrap().path();
            let source = fs::read_to_string(&path).unwrap();
            let mut component = String::new();
            let mut read = 0;
            for line in source.lines() {
                let declaration = line.trim_start();
                if let Some(rest) = ["export component ", "component ", "export global "]
                    .iter()
                    .find_map(|keyword| declaration.strip_prefix(keyword))
                {
                    component = rest.split_whitespace().next().unwrap().to_owned();
                }
                for call in line.split("@tr(\"").skip(1) {
                    let text = call.split('"').next().unwrap();
                    let after = call[text.len() + 1..].trim_start();
                    assert!(
                        !text.ends_with('\\') && !after.starts_with("=>"),
                        "{}: a form of @tr this test cannot read: {line}",
                        path.display()
                    );
                    // Labels say "Label: n", never a plural form.
                    assert!(
                        !after.starts_with('|'),
                        "{}: a plural form: {line}",
                        path.display()
                    );
                    texts.push((component.clone(), text.to_owned()));
                    read += 1;
                }
            }
            assert_eq!(
                source.matches("@tr").count(),
                read,
                "{}: an @tr this test cannot read",
                path.display()
            );
        }
        texts
    }

