/// Okapi's own license.
const LICENSE: &str = include_str!("../../../LICENSE");
/// What the interface itself embeds (Slint, Lucide), beyond what the rules
/// do (`okapi_rules::THIRD_PARTY_NOTICES`).
const INTERFACE_NOTICES: &str = include_str!("../THIRD_PARTY_NOTICES");
/// The licenses of the crates built into this binary (`cargo about`).
const CRATES_NOTICES: &str = include_str!("../CRATES_NOTICES");
/// Every license text the About screen shows, in order.
const LICENSE_TEXTS: [&str; 4] = [
    LICENSE,
    okapi_rules::THIRD_PARTY_NOTICES,
    INTERFACE_NOTICES,
    CRATES_NOTICES,
];

/// Every license text, a paragraph each: the About screen lays out only
/// those in view.
fn license_paragraphs() -> Vec<SharedString> {
    LICENSE_TEXTS
        .iter()
        .flat_map(|text| text.split("\n\n"))
        // Never `trim`: a license's own indentation is kept.
        .map(|paragraph| paragraph.trim_matches('\n'))
        .filter(|paragraph| !paragraph.trim().is_empty())
        .map(SharedString::from)
        .collect()
}

/// The application id the window carries under Wayland and X11. GNOME under
/// Wayland ignores the window's icon and takes the one of the desktop entry
/// of this name (`packaging/linux/`).
const APP_ID: &str = "io.github.cryborg.Okapi";

/// How long the dashboard waits for a filesystem to tell its space: a share
/// that does not answer within it is said to.
const SPACE_TIMEOUT: Duration = Duration::from_secs(2);

/// The screens a window holds, beyond what Slint does alone.
struct Screens {
    window: AppWindow,
    cleaner: CleanerScreen,
    home: DashboardScreen,
    settings: SettingsScreen,
    apps: AppsScreen,
    duplicates: DuplicatesScreen,
    large_files: LargeFilesScreen,
}

/// The window in `language`, filled with what it shows of Okapi itself, its
/// cleaner reading, scanning and cleaning through `seams`, its settings
/// read and written through them too, its Home page reading through `home`.
fn window(
    mut seams: Seams,
    home: DashboardSeams,
    language: Language,
) -> Result<Screens, slint::PlatformError> {
    let window = AppWindow::new()?;
    // Refused while no component exists (no platform yet), and read only when
    // the window is shown: between the two.
    if let Err(error) = slint::set_xdg_app_id(APP_ID) {
        tracing::error!(%error, app_id = APP_ID, "application id not set");
    }
    // Slint's own texts in the language of the rules' labels: the French
    // source is the bundle's empty language. Known once a component exists.
    let bundle = match language {
        Language::French => "",
        Language::English => "en",
    };
    if let Err(error) = slint::select_bundled_translation(bundle) {
        tracing::error!(%error, ?language, "interface language not applied");
    }
    window.set_version(env!("CARGO_PKG_VERSION").into());
    window.set_license_name(env!("CARGO_PKG_LICENSE").into());
    window.set_repository(env!("CARGO_PKG_REPOSITORY").into());
    window.set_license_paragraphs(ModelRc::from(Rc::new(VecModel::from(license_paragraphs()))));
    let settings = SettingsScreen::attach(&window, seams.settings.clone());
    // What the cleaner reads of the settings waits for the changes under
    // way, and is refused while one is stuck, or once after one failed: an
    // exclusion just added is never missed by the next cleaning without a
    // word.
    let read = Rc::clone(&seams.read);
    let settled = settings.clone();
    let read_settled = move |tell: bool| {
        let waited = if tell {
            settled.wait_for_writes()
        } else {
            settled.look_at_writes()
        };
        if let Err(unsaved) = waited {
            tracing::error!(
                ?unsaved,
                "the last change of the settings is not on the disk: not read, nothing starts"
            );
            return Err(match unsaved {
                settings::Unsaved::Pending => cleaner::Problem::SettingsSaving,
                settings::Unsaved::Failed => cleaner::Problem::SettingsUnsaved,
            });
        }
        read()
    };
    let read_settled = Rc::new(read_settled);
    let telling = Rc::clone(&read_settled);
    seams.read = Rc::new(move || telling(true));
    let disk = DiskUsageScreen::attach(&window, seams.disk.clone(), language);
    // The settings as the cleaner reads them, its writes waited for: an
    // exclusion just added is never missed by a search nor a move.
    let settled_read = Rc::clone(&seams.read);
    let exclusions: user_files::ReadExclusions =
        Rc::new(move || settled_read().map(|inputs| inputs.exclusions));
    let duplicates = DuplicatesScreen::attach(
        &window,
        seams.duplicates.clone(),
        Rc::clone(&exclusions),
        language,
    );
    let large_files =
        LargeFilesScreen::attach(&window, seams.large_files.clone(), exclusions, language);
    let updates = UpdatesScreen::attach(&window, seams.updates.clone());
    let history = HistoryScreen::attach(&window, seams.history.clone());
    // The same settings: never a leftover where the user excluded. Read in
    // the background, they leave a failure to be said to the cleaner.
    let apps = AppsScreen::attach(
        &window,
        seams.apps.clone(),
        Rc::new(move || read_settled(false).map(|inputs| inputs.exclusions)),
        language,
    );
    let screen = CleanerScreen::attach(&window, seams, language);
    // Once the writes are done, the cleaner reads them again, and the
    // leftovers they held back are looked for: a refusal they caused is
    // lifted, or a failure said there. The cleaner first: it is the one
    // told of a failure, the leftovers then read the file as it is.
    let refreshed = screen.clone();
    let written_apps = apps.clone();
    settings.when_written(Rc::new(move || {
        refreshed.refresh();
        written_apps.settings_written();
    }));
    close_when_done(&window, screen.clone(), apps.clone(), updates.clone());
    tracing::debug!(page = ?window.get_page(), "page shown");
    let sized = window.as_weak();
    window.on_sidebar_shown(move |chosen_folded, narrow| {
        let window = sized.upgrade();
        let size = window.as_ref().map(|window| window.window().size());
        let scale = window.as_ref().map(|window| window.window().scale_factor());
        tracing::debug!(chosen_folded, narrow, ?size, ?scale, "sidebar shown");
    });
    let followers = Followers {
        disk,
        duplicates: duplicates.clone(),
        large_files: large_files.clone(),
        updates,
        apps: apps.clone(),
        history,
    };
    let dashboard = attach_home(&window, &screen, followers, home);
    Ok(Screens {
        window,
        cleaner: screen,
        home: dashboard,
        settings,
        apps,
        duplicates,
        large_files,
    })
}

/// Closes `window` once what must be written is: the cleaner's history line
/// first, then an uninstallation's; an installation of updates goes on
/// without Okapi, which is traced.
fn close_when_done(
    window: &AppWindow,
    cleaner: CleanerScreen,
    apps: AppsScreen,
    updates: UpdatesScreen,
) {
    window.window().on_close_requested(move || {
        let response = match cleaner.close_requested() {
            slint::CloseRequestResponse::HideWindow => apps.close_requested(),
            held @ slint::CloseRequestResponse::KeepWindowShown => held,
        };
        if matches!(response, slint::CloseRequestResponse::HideWindow) {
            updates.closing();
        }
        response
    });
}

/// The screens that follow the page shown, beside the Home page.
struct Followers {
    disk: DiskUsageScreen,
    duplicates: DuplicatesScreen,
    large_files: LargeFilesScreen,
    updates: UpdatesScreen,
    apps: AppsScreen,
    history: HistoryScreen,
}

/// Binds the Home page to `window`: it follows the page shown, its
/// "Analyser" asks `cleaner`, it hears what `cleaner` does, and its updates
/// widget reads by the updates screen. The other screens follow the page
/// shown too, and the History hears a cleaning end.
fn attach_home(
    window: &AppWindow,
    screen: &CleanerScreen,
    followers: Followers,
    home: DashboardSeams,
) -> DashboardScreen {
    let dashboard = DashboardScreen::attach(window, home);
    let volumes = dashboard.clone();
    // Held here, by the page's callback, as long as the window is.
    let Followers {
        disk,
        duplicates,
        large_files,
        updates,
        apps,
        history,
    } = followers;
    disk.read_volumes_from(Rc::new(move || volumes.volumes()));
    let reading = updates.clone();
    dashboard.read_updates_with(Rc::new(move || reading.read_if_due()));
    let history_told = history.clone();
    let heard = dashboard.clone();
    let cleaner = screen.clone();
    let shown_home = dashboard.clone();
    window.on_page_shown(move |page| {
        tracing::debug!(?page, "page shown");
        // The settings may have changed since the screen was last shown.
        if page == Page::Cleaner {
            cleaner.refresh();
        }
        shown_home.page_shown(page);
        disk.page_shown(page);
        duplicates.page_shown(page);
        large_files.page_shown(page);
        updates.page_shown(page);
        apps.page_shown(page);
        history.page_shown(page);
    });
    let analyzing = screen.clone();
    window
        .global::<ui::Dashboard>()
        .on_analyze(move || analyzing.analyze_default());
    screen.listen(Rc::new(move |event| match event {
        CleanerEvent::AnalysisDone(summary) => heard.analysis_done(summary),
        CleanerEvent::CleaningDone { freed, at } => {
            heard.cleaning_done(freed, at);
            history_told.cleaning_done();
        }
    }));
    dashboard
}

/// What the Home page reads on this machine: its directories, its time
/// zone, and the readings of a sampler kept as long as the page is.
fn home_seams(language: Language) -> DashboardSeams {
    let (sink, readings) = mpsc::channel();
    let commands: Box<dyn Fn(Command)> = match Sampler::start(sink, language, SPACE_TIMEOUT) {
        Ok(sampler) => Box::new(move |command| sampler.send(command)),
        Err(error) => {
            // Its sink is gone with it: the page says every reading is
            // unavailable.
            tracing::error!(%error, "dashboard sampler not started");
            Box::new(|_| {})
        }
    };
    let config_directory = okapi_platform::config_directory();
    DashboardSeams {
        config_directory: config_directory.clone(),
        state_directory: okapi_platform::state_directory(),
        zone: dashboard::system_zone(),
        now: jiff::Timestamp::now,
        commands,
        samples: readings,
        save: config_directory.map(|directory| -> dashboard::Write {
            Box::new(move |layout| layout.save(&directory).is_ok())
        }),
    }
}

/// A diagnostic for whoever launched the app from a terminal, in English: no
/// window can say it (not yet, or not at all). Never panics on a closed
/// standard error.
fn diagnostic(message: &str) {
    let _ = writeln!(io::stderr(), "okapi-app: {message}");
}

fn main() -> ExitCode {
    // Never as root, as the command line: its journal would belong to root in
    // the user's directory.
    if okapi_platform::running_as_root() {
        diagnostic("refusing to run as root");
        return ExitCode::FAILURE;
    }
    let on_write_failure: journal::WriteFailure = Box::new(|error| {
        diagnostic(&format!("the journal can no longer be written: {error}"));
    });
    let opening = match journal::start(journal::APP_FILE, false, on_write_failure) {
        Ok((_, opening)) => Some(opening),
        Err(unavailable) => {
            diagnostic(&format!("running without a journal: {unavailable}"));
            None
        }
    };
    let _app = tracing::info_span!("app", pid = std::process::id()).entered();
    if let Some(opening) = &opening {
        opening.trace();
    }
    journal::trace_panics();
    let session = Language::of_session(|name| std::env::var_os(name));
    let language =
        okapi_store::Settings::language(okapi_platform::config_directory().as_deref(), session);
    tracing::info!(
        version = env!("CARGO_PKG_VERSION"),
        ?language,
        session_language = ?session,
        session = ?SESSION_VARIABLES.map(|name| (name, std::env::var_os(name))),
        "app started"
    );
    let Screens {
        window,
        cleaner: screen,
        home,
        settings,
        apps,
        duplicates,
        large_files,
    } = match window(Seams::system(), home_seams(language), language) {
        Ok(window) => window,
        Err(error) => {
            tracing::error!(error = %error, detail = ?error, "window not created");
            diagnostic(&format!("no window: {error}"));
            return ExitCode::FAILURE;
        }
    };
    tracing::info!("window created");
    let kept_sidebar = sidebar::KeptSidebar::attach(&window, okapi_platform::state_directory());
    screen.keep_selections(kept_selections::KeptSelections::start(
        okapi_platform::state_directory(),
    ));
    let ran = window.run();
    screen.shut_down();
    duplicates.shut_down();
    large_files.shut_down();
    apps.shut_down();
    home.shut_down();
    kept_sidebar.shut_down();
    settings.shut_down();
    match ran {
        Ok(()) => {
            tracing::info!("app closed");
            ExitCode::SUCCESS
        }
        Err(error) => {
            tracing::error!(error = %error, detail = ?error, "event loop failed");
            diagnostic(&format!("the event loop failed: {error}"));
            ExitCode::FAILURE
        }
    }
}

/// The window at the mockup's size: the testing backend makes it narrower
/// than the sidebar's threshold, which would fold it.
#[cfg(test)]
fn wide_window(seams: Seams, home: DashboardSeams, language: Language) -> Screens {
    const MOCKUP: slint::PhysicalSize = slint::PhysicalSize::new(1280, 800);
    i_slint_backend_testing::init_no_event_loop();
    let built = window(seams, home, language).unwrap();
    built.window.window().set_size(MOCKUP);
    // `changed` handlers run on the next turn of the event loop.
    slint::platform::update_timers_and_animations();
    built
}

