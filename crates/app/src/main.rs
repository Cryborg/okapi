/// Okapi's own license.
const LICENSE: &str = include_str!("../../../LICENSE");
/// What the interface itself embeds (Slint, Lucide), beyond what the rules
/// do (`okapi_rules::THIRD_PARTY_NOTICES`).
const INTERFACE_NOTICES: &str = include_str!("../THIRD_PARTY_NOTICES");
/// How long the dashboard waits for a filesystem to tell its space: a share
/// that does not answer within it is said to.
const SPACE_TIMEOUT: Duration = Duration::from_secs(2);

/// The window in `language`, filled with what it shows of Okapi itself, its
/// cleaner reading, scanning and cleaning through `seams`, its Home page
/// reading through `home`.
fn window(
    seams: Seams,
    home: DashboardSeams,
    language: Language,
) -> Result<(AppWindow, CleanerScreen, DashboardScreen), slint::PlatformError> {
    let window = AppWindow::new()?;
    // Slint's own texts in the language of the rules' labels: the French
    // source is the bundle's empty language. Known once a component exists.
    let bundle = match language {
        Language::French => "",
        Language::English => "en",
    };
    if let Err(error) = slint::select_bundled_translation(bundle) {
        tracing::error!(%error, ?language, "interface language not applied");
    }
    window.set_version(env!("CARGO_PKG_VERSION").into());
    window.set_license_name(env!("CARGO_PKG_LICENSE").into());
    window.set_repository(env!("CARGO_PKG_REPOSITORY").into());
    window.set_license_texts(
        [LICENSE, okapi_rules::THIRD_PARTY_NOTICES, INTERFACE_NOTICES]
            .join("\n\n")
            .into(),
    );
    let screen = CleanerScreen::attach(&window, seams, language);
    let closing = screen.clone();
    window
        .window()
        .on_close_requested(move || closing.close_requested());
    tracing::debug!(page = ?window.get_page(), "page shown");
    let sized = window.as_weak();
    window.on_sidebar_shown(move |chosen_folded, narrow| {
        let window = sized.upgrade();
        let size = window.as_ref().map(|window| window.window().size());
        let scale = window.as_ref().map(|window| window.window().scale_factor());
        tracing::debug!(chosen_folded, narrow, ?size, ?scale, "sidebar shown");
    });
    let dashboard = attach_home(&window, &screen, home);
    Ok((window, screen, dashboard))
}

/// Binds the Home page to `window`: it follows the page shown, its
/// "Analyser" asks `cleaner`, and it hears what `cleaner` does.
fn attach_home(
    window: &AppWindow,
    screen: &CleanerScreen,
    home: DashboardSeams,
) -> DashboardScreen {
    let dashboard = DashboardScreen::attach(window, home);
    let heard = dashboard.clone();
    let cleaner = screen.clone();
    let shown_home = dashboard.clone();
    window.on_page_shown(move |page| {
        tracing::debug!(?page, "page shown");
        // The settings may have changed since the screen was last shown.
        if page == Page::Cleaner {
            cleaner.refresh();
        }
        shown_home.page_shown(page);
    });
    let analyzing = screen.clone();
    window
        .global::<ui::Dashboard>()
        .on_analyze(move || analyzing.analyze_default());
    screen.listen(Rc::new(move |event| match event {
        CleanerEvent::AnalysisDone(summary) => heard.analysis_done(summary),
        CleanerEvent::CleaningDone { freed, at } => heard.cleaning_done(freed, at),
    }));
    dashboard
}

/// What the Home page reads on this machine: its directories, its time
/// zone, and the readings of a sampler kept as long as the page is.
fn home_seams(language: Language) -> DashboardSeams {
    let (sink, readings) = mpsc::channel();
    let commands: Box<dyn Fn(Command)> = match Sampler::start(sink, language, SPACE_TIMEOUT) {
        Ok(sampler) => Box::new(move |command| sampler.send(command)),
        Err(error) => {
            // Its sink is gone with it: the page says every reading is
            // unavailable.
            tracing::error!(%error, "dashboard sampler not started");
            Box::new(|_| {})
        }
    };
    let config_directory = okapi_platform::config_directory();
    DashboardSeams {
        config_directory: config_directory.clone(),
        state_directory: okapi_platform::state_directory(),
        zone: dashboard::system_zone(),
        now: jiff::Timestamp::now,
        commands,
        samples: readings,
        save: config_directory.map(|directory| -> dashboard::Write {
            Box::new(move |layout| layout.save(&directory).is_ok())
        }),
    }
}

/// A diagnostic for whoever launched the app from a terminal, in English: no
/// window can say it (not yet, or not at all). Never panics on a closed
/// standard error.
fn diagnostic(message: &str) {
    let _ = writeln!(io::stderr(), "okapi-app: {message}");
}

fn main() -> ExitCode {
    // Never as root, as the command line: its journal would belong to root in
    // the user's directory.
    if okapi_platform::running_as_root() {
        diagnostic("refusing to run as root");
        return ExitCode::FAILURE;
    }
    let on_write_failure: journal::WriteFailure = Box::new(|error| {
        diagnostic(&format!("the journal can no longer be written: {error}"));
    });
    let rotation = match journal::start(journal::APP_FILE, false, on_write_failure) {
        Ok((_, rotation)) => Some(rotation),
        Err(unavailable) => {
            diagnostic(&format!("running without a journal: {unavailable}"));
            None
        }
    };
    let _app = tracing::info_span!("app", pid = std::process::id()).entered();
    if let Some(rotation) = &rotation {
        rotation.trace();
    }
    journal::trace_panics();
    // The language, from the variables gettext reads (D-7).
    let language = Language::of_session(|name| std::env::var_os(name));
    tracing::info!(
        version = env!("CARGO_PKG_VERSION"),
        ?language,
        session = ?SESSION_VARIABLES.map(|name| (name, std::env::var_os(name))),
        "app started"
    );
    let (window, screen, home) = match window(Seams::system(), home_seams(language), language) {
        Ok(window) => window,
        Err(error) => {
            tracing::error!(error = %error, detail = ?error, "window not created");
            diagnostic(&format!("no window: {error}"));
            return ExitCode::FAILURE;
        }
    };
    tracing::info!("window created");
    let fold = sidebar::KeptFold::attach(&window, okapi_platform::state_directory());
    screen.keep_selections(kept_selections::KeptSelections::start(
        okapi_platform::state_directory(),
    ));
    let ran = window.run();
    screen.shut_down();
    home.shut_down();
    fold.shut_down();
    match ran {
        Ok(()) => {
            tracing::info!("app closed");
            ExitCode::SUCCESS
        }
        Err(error) => {
            tracing::error!(error = %error, detail = ?error, "event loop failed");
            diagnostic(&format!("the event loop failed: {error}"));
            ExitCode::FAILURE
        }
    }
}

/// The window at the mockup's size: the testing backend makes it narrower
/// than the sidebar's threshold, which would fold it.
#[cfg(test)]
fn wide_window(
    seams: Seams,
    home: DashboardSeams,
    language: Language,
) -> (AppWindow, CleanerScreen, DashboardScreen) {
    const MOCKUP: slint::PhysicalSize = slint::PhysicalSize::new(1280, 800);
    i_slint_backend_testing::init_no_event_loop();
    let built = window(seams, home, language).unwrap();
    built.0.window().set_size(MOCKUP);
    // `changed` handlers run on the next turn of the event loop.
    slint::platform::update_timers_and_animations();
    built
}

